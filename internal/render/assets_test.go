func TestReaderJavaScript(t *testing.T) {
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node is not installed; browser assets are still checked by Go tests")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	output, err := exec.CommandContext(ctx, node, "--test", "testdata/reader.test.cjs").CombinedOutput()
	if err != nil {
		t.Fatalf("reader/KaTeX JavaScript tests: %v\n%s", err, output)
	}
}

func TestAssets(t *testing.T) {
	assets := Assets()
	for _, name := range []string{"reader.js", "syntax.css", "katex.min.js", "katex.min.css", "LICENSE-KaTeX", "LICENSE-Chroma", "fonts/OFL.txt"} {
		data, err := fs.ReadFile(assets, name)
		if err != nil || len(data) == 0 {
			t.Errorf("missing/empty root asset %s: %v", name, err)
		}
	}
	// Hashes of the unmodified files from the integrity-verified katex@0.19.1 tarball.
	for name, expected := range map[string]string{
		"katex.min.js":  "fa140498b8cfc8302cbe5e7cb1bdbc1f952bc38b3fa258ede09e73edbf9a74bc",
		"katex.min.css": "00e0b094171b07f58422075f469b4feac2b2f7bce1aeec943c08da4d697f4dcf",
	} {
		data, err := fs.ReadFile(assets, name)
		if err != nil {
			t.Fatal(err)
		}
		if got := fmt.Sprintf("%x", sha256.Sum256(data)); got != expected {
			t.Errorf("vendored %s differs from pinned KaTeX 0.19.1: %s", name, got)
		}
	}
	css, err := fs.ReadFile(assets, "katex.min.css")
	if err != nil {
		t.Fatal(err)
	}
	fonts := make(map[string]bool)
	for _, match := range regexp.MustCompile(`url\(([^)]+)\)`).FindAllSubmatch(css, -1) {
		name := string(match[1])
		if !strings.HasPrefix(name, "fonts/") || !fs.ValidPath(name) {
			t.Fatalf("non-local KaTeX asset reference: %s", name)
		}
		if data, err := fs.ReadFile(assets, name); err != nil || len(data) == 0 {
			t.Errorf("missing font %s: %v", name, err)
		}
		fonts[name] = true
	}
	if len(fonts) != 60 {
		t.Errorf("got %d CSS-referenced fonts, want all 60", len(fonts))
	}
	if _, err := fs.ReadFile(assets, "../go.mod"); err == nil {
		t.Error("asset filesystem allowed traversal")
	}
	if _, err := fs.ReadFile(assets, "static/reader.js"); err == nil {
		t.Error("Assets did not expose files at FS root")
	}
}

func TestSyntaxCSSMatchesFormatter(t *testing.T) {
	var generated bytes.Buffer
	if err := codeFormatter().WriteCSS(&generated, codeStyle); err != nil {
		t.Fatal(err)
	}
	css, err := fs.ReadFile(Assets(), "syntax.css")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasSuffix(css, generated.Bytes()) {
		t.Error("syntax.css is stale; run go run generate_syntax.go in internal/render")
	}
	if !bytes.Contains(css, []byte(".syntax-chroma .syntax-k")) || bytes.Contains(css, []byte("https://")) {
		t.Error("highlighting CSS is missing or references a remote resource")
	}
}

func TestAssetsHTTPMount(t *testing.T) {
	handler := http.StripPrefix("/assets/reader/", http.FileServer(http.FS(Assets())))
	for _, name := range []string{"reader.js", "katex.min.js", "syntax.css", "katex.min.css", "fonts/KaTeX_Main-Regular.woff2"} {
		recorder := httptest.NewRecorder()
		handler.ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, "/assets/reader/"+name, nil))
		if recorder.Code != http.StatusOK || recorder.Body.Len() == 0 {
			t.Errorf("asset mount failed for %s: %d", name, recorder.Code)
		}
	}
}
