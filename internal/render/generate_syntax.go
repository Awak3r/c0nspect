//go:build ignore

// Run with go run generate_syntax.go from this directory.
package main

import (
	"bytes"
	"log"
	"os"

	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

func main() {
	var output bytes.Buffer
	output.WriteString(`/* Generated by go run generate_syntax.go; Chroma v2.27.0, github theme. */
pre.syntax-chroma { padding: 1rem; overflow-x: auto; tab-size: 4; }
.math { white-space: pre-wrap; overflow-wrap: anywhere; }
.math-display { display: block; margin: 1rem 0; overflow-x: auto; }
.math .katex { white-space: normal; overflow-wrap: normal; }
pre.math-source { white-space: pre-wrap; overflow-wrap: anywhere; }
.task-marker { margin-inline-end: 0.25em; }
`)
	formatter := chromahtml.New(chromahtml.WithClasses(true), chromahtml.ClassPrefix("syntax-"),
		chromahtml.PreventSurroundingPre(true))
	if err := formatter.WriteCSS(&output, styles.Get("github")); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("static/syntax.css", output.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
